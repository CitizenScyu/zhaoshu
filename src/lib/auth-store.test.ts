import { describe, expect, it } from 'vitest';
import { AUTH_SCHEMA_VERSION, initializeAuthSchema } from './auth-store';

type Query = { text: string };

function fakeSql() {
  const batches: Query[][] = [];
  const tx = (parts: TemplateStringsArray, ...values: unknown[]): Query => ({
    text: parts.reduce((text, part, index) => text + part + (index < values.length ? '?' : ''), ''),
  });
  return {
    batches,
    sql: {
      transaction: async (builder: (query: typeof tx) => Query[]) => {
        batches.push(builder(tx));
        return [];
      },
    },
  };
}

describe('auth schema initialization', () => {
  it('defines a versioned, locked, closed-by-default owner skeleton', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(AUTH_SCHEMA_VERSION).toBe(7);
    expect(text).toContain('pg_advisory_xact_lock');
    expect(text).toContain('GENERATED BY DEFAULT AS IDENTITY (START WITH 2)');
    expect(text).toContain("VALUES (1, 'owner', 'owner', true, true, true)");
    expect(text).toContain("registration_mode text NOT NULL DEFAULT 'closed'");
    expect(text).toContain('members_enabled boolean NOT NULL DEFAULT false');
    expect(text).toContain('conflicts with the fixed owner identity');
    expect(text).not.toContain('DATABASE_URL');
  });

  it('adds version 2 sessions and rate limit tables without dropping history', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(text).toContain('CREATE TABLE IF NOT EXISTS sessions');
    expect(text).toContain("token_hash char(64) PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$')");
    expect(text).toContain("CHECK (auth_method IN ('password', 'owner_token'))");
    expect(text).toContain('CHECK ((auth_method = \'owner_token\') = (user_id = 1))');
    expect(text).toContain('sessions_user_created_idx');
    expect(text).toContain('sessions_expires_idx');
    expect(text).toContain('CREATE TABLE IF NOT EXISTS auth_rate_limits');
    expect(text).toContain('PRIMARY KEY (scope, key_hash, window_start)');
    expect(text).toContain('auth_rate_limits_expires_idx');
    expect(text).toContain('VALUES (2)');
    expect(text).toContain('newer than supported version 7');
    // 幂等扩展：不删表、不删列、不动 v1 结构。
    expect(text).not.toMatch(/DROP (TABLE|COLUMN)/);
    expect(text).toContain('DROP CONSTRAINT %I');
    expect(text).toContain('DROP INDEX %I.%I');
  });

  it('uses the same idempotent transaction for repeated and concurrent initialization', async () => {
    const fake = fakeSql();
    await Promise.all([initializeAuthSchema(fake.sql as never), initializeAuthSchema(fake.sql as never)]);
    expect(fake.batches).toHaveLength(2);
    expect(fake.batches[0].map((query) => query.text)).toEqual(fake.batches[1].map((query) => query.text));
    for (const batch of fake.batches) {
      expect(batch[0].text).toContain('pg_advisory_xact_lock');
      expect(batch.map((q) => q.text).join(' ')).toContain('IF NOT EXISTS (SELECT 1 FROM auth_schema_migrations WHERE version = 4)');
    }
  });

  it('adds the owner-compatible personal data migration in the locked transaction', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(text).toContain("to_regclass('profile')");
    expect(text).toContain('profile contains an unexpected non-owner id');
    expect(text).toContain('recommendations legacy table unique constraint has drifted');
    expect(text).toContain('recommendations legacy explicit unique index has drifted');
    expect(text).toContain('auth_schema_migrations WHERE version = 3');
    expect(text).toContain('ALTER TABLE profile ALTER COLUMN id DROP DEFAULT');
    expect(text).toContain('profile_user_fk');
    expect(text).toContain('recommendations_user_fk');
    expect(text).toContain('feedback_user_fk');
    expect(text).toContain('recommendations_user_book_query_idx');
    expect(text).toContain('recommendations_book_query_idx');
    expect(text).toContain('VALUES (3)');
    expect(text).toContain('newer than supported version 7');
    expect(text).not.toMatch(/DROP (TABLE|COLUMN)/);
    expect(text).toContain('DROP CONSTRAINT %I');
    expect(text).toContain('DROP INDEX %I.%I');
  });

  it('adds download ownership and fails closed on duplicate active work without deleting rows', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(text).toContain('ALTER TABLE download_tasks ADD COLUMN IF NOT EXISTS user_id integer');
    expect(text).toContain('UPDATE download_tasks SET user_id = 1 WHERE user_id IS NULL');
    expect(text).toContain('download_tasks_user_fk');
    expect(text).toContain('CREATE UNIQUE INDEX download_tasks_active_book_idx ON download_tasks (book_id)');
    expect(text).toContain("WHERE status IN ('pending', 'running')");
    expect(text).not.toContain('DELETE FROM download_tasks');
    expect(text).toContain('INSERT INTO auth_schema_migrations (version) VALUES (5)');
  });

  it('v6 增加邀请码表与外键，且不改动 v5 之前的语句', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(text).toContain('registration_invites');
    expect(text).toContain("code_hash ~ '^[0-9a-f]{64}$'");
    expect(text).toContain('CHECK ((used_by IS NULL) = (used_at IS NULL))');
    expect(text).toContain('CHECK (expires_at IS NULL OR expires_at > created_at)');
    expect(text).toContain('users_created_via_invite_fk');
    expect(text).toContain('existing users reference unknown invite codes');
    expect(text).toContain('CREATE INDEX IF NOT EXISTS registration_invites_created_idx');
    expect(text).toContain('INSERT INTO auth_schema_migrations (version) VALUES (6)');
    // 原文永不落库：v6 里不能出现明文的邀请码列。
    expect(text).not.toContain('code text');
    expect(text).not.toMatch(/DROP (TABLE|COLUMN)/);
  });

  it('v7 增加系统任务、事件幂等、attempt 与租约 fencing 契约', async () => {
    const fake = fakeSql();
    await initializeAuthSchema(fake.sql as never);
    const text = fake.batches[0].map((query) => query.text).join('\n');
    expect(text).toContain('auth_schema_migrations WHERE version = 7');
    expect(text).toContain("ADD COLUMN IF NOT EXISTS requested_by text NOT NULL DEFAULT 'user'");
    expect(text).toContain('ALTER TABLE download_tasks ALTER COLUMN user_id DROP NOT NULL');
    expect(text).toContain("CHECK (requested_by IN ('user', 'system'))");
    expect(text).toContain("requested_by = 'system' AND user_id IS NULL");
    expect(text).toContain('download_tasks_system_active_book_idx');
    expect(text).toContain('download_tasks_system_event_idx');
    expect(text).toContain('ADD COLUMN IF NOT EXISTS attempt_count integer NOT NULL DEFAULT 1');
    expect(text).toContain('ADD COLUMN IF NOT EXISTS retry_of integer');
    expect(text).toContain('ADD COLUMN IF NOT EXISTS lease_generation bigint NOT NULL DEFAULT 0');
    expect(text).toContain("ADD COLUMN IF NOT EXISTS lease_owner text NOT NULL DEFAULT ''");
    expect(text).toContain('INSERT INTO auth_schema_migrations (version) VALUES (7)');
  });
});
